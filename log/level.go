package log

// OutputConfig.Level 可接受的日志级别字符串。
const (
	// LevelDebug 是 debug 级别字符串。
	LevelDebug = "debug"
	// LevelInfo 是 info 级别字符串。
	LevelInfo = "info"
	// LevelWarn 是 warn 级别字符串。
	LevelWarn = "warn"
	// LevelError 是 error 级别字符串。
	LevelError = "error"
	// LevelFatal 是 fatal 级别字符串。
	LevelFatal = "fatal"
)
